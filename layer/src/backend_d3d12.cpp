// Shader constants: must match cbuffer Params in shaders/smooth.hlsl (36 x 32-bit).
struct SmoothConsts {
    float cx, cy, ha, hb, shape, band, strength, edge;
    uint32_t width, height, tile, outer;
    uint32_t slice, flags, lens, scale;
    float textX, textY, pad0, pad1;
    uint32_t text[16];
};
static_assert(sizeof(SmoothConsts) == 144, "root constants are 36 dwords");
constexpr UINT kConstDwords = 36;

// Formats a swapchain may be viewed with directly. A typeless or unusual format is not smoothed.
bool smoothable_format(DXGI_FORMAT f) {
    switch (f) {
        case DXGI_FORMAT_R8G8B8A8_UNORM: case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
        case DXGI_FORMAT_B8G8R8A8_UNORM: case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
        case DXGI_FORMAT_B8G8R8X8_UNORM: case DXGI_FORMAT_B8G8R8X8_UNORM_SRGB:
        case DXGI_FORMAT_R10G10B10A2_UNORM: case DXGI_FORMAT_R11G11B10_FLOAT:
        case DXGI_FORMAT_R16G16B16A16_FLOAT: case DXGI_FORMAT_R16G16B16A16_UNORM:
            return true;
        default:
            return false;
    }
}

