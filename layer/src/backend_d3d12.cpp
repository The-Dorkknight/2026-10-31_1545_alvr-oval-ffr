// OvalFFR D3D12 backend (Windows).
//
// How it works (see docs/ARCHITECTURE.md):
//   * needs Variable Rate Shading tier 2 (shading-rate image). Anything less: no-op.
//   * builds an R8_UINT shading-rate image per eye from ovalffr::make_mask()
//   * patches two shared COM vtable slots once per process:
//       ID3D12Device::CreateRenderTargetView            (remember handle -> size)
//       ID3D12GraphicsCommandList::OMSetRenderTargets   (bind the rate image)
//     The originals are always called first; patches are never removed.
//   * when an eye-sized render target is bound, it sets the rate image; when a
//     different target is bound on the same list, it clears it again.
//
//   * optional "Smooth periphery" (config smooth=1, off by default): when the app hands an eye
//     image back (xrReleaseSwapchainImage) a small full-screen pass is queued on the app's own
//     queue, behind its drawing. It copies the image and blends the blocky 2x2 / 4x4 pixels into a
//     bilinear upscale (layer/shaders/smooth.hlsl). The shader is compiled at run time by
//     d3dcompiler_47.dll. Any failure switches only the smoothing off, never the game.
//   * the same release-time command list also runs the VRS check (a compute pass that samples the
//     low-res zones and counts exact-copy blocks, read back a few frames later) and draws the
//     in-headset fps box and zone highlight (alpha-blended, no copy needed for text only).
//
// STATUS: compile-checked with mingw-w64 only. NOT yet run against a real D3D12 game.
