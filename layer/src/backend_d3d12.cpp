std::unique_ptr<Backend> create_backend(const XrSessionCreateInfo* ci, std::string* why) {
    for (const XrBaseInStructure* p = (const XrBaseInStructure*)ci->next; p; p = p->next) {
        if (p->type == XR_TYPE_GRAPHICS_BINDING_D3D12_KHR) {
            auto* b = (const XrGraphicsBindingD3D12KHR*)p;
            std::unique_ptr<D3D12Backend> be(new D3D12Backend());
            if (!be->init(b->device, b->queue, why)) return nullptr;
            return std::unique_ptr<Backend>(be.release());
        }
    }
    *why = "app does not use D3D12 (D3D11 and Vulkan backends are on the roadmap)";
    return nullptr;
}

