def encode(rows):
    words = [0, 0]
    for r, line in enumerate(rows.split("|")):
        assert len(line) == 5, rows
        for c, ch in enumerate(line):
            if ch == "#":
                if r < 4:
                    words[0] |= 1 << (r * 5 + c)
                else:
                    words[1] |= 1 << ((r - 4) * 5 + c)
    return words


def main():
    chars = "".join(GLYPHS.keys())
    table = [encode(GLYPHS[c]) for c in chars]
    hlsl = ("// FONT-BEGIN (generated by tools/gen_font.py - do not edit by hand)\n"
            "#define FONT_COUNT %d\n" % len(table) +
            "static const uint2 kFont[%d] = {\n" % len(table) +
            ",\n".join("    uint2(0x%05xu, 0x%04xu)  /* %r */" % (a, b, c) for (a, b), c in zip(table, chars)) +
            "\n};\n// FONT-END")
    p = os.path.join(ROOT, "layer", "shaders", "smooth.hlsl")
    with open(p, encoding="utf-8") as f:
        s = f.read()
    s, n = re.subn(r"// FONT-BEGIN.*?// FONT-END", lambda m: hlsl, s, flags=re.S)
    assert n == 1, "markers not found in smooth.hlsl"
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)
    esc = chars.replace("\\", "\\\\").replace('"', '\\"')
    cpp = ("// Generated by tools/gen_font.py - do not edit by hand. Same table as layer/shaders/smooth.hlsl.\n"
           "#pragma once\n#include <cstdint>\n\nnamespace ovalffr {\n\n"
           "constexpr char kFontChars[] = \"%s\";\n" % esc +
           "constexpr int kFontCount = %d;\n" % len(table) +
           "constexpr uint32_t kFont[%d][2] = {\n" % len(table) +
           ",\n".join("    {0x%05xu, 0x%04xu}" % (a, b) for a, b in table) +
           "\n};\n\n} // namespace ovalffr\n")
    with open(os.path.join(ROOT, "layer", "src", "ovalffr_font.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(cpp)
    print("font: %d glyphs" % len(table))


if __name__ == "__main__":
    main()
